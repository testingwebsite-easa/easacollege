/**
 * Keyword-based fallback resolver
 */
export const getDomainHeroImage = (pageKey = '', title = '', explicitImage = null) => {
    // If a valid non-generic explicit image is provided, use it
    if (explicitImage && typeof explicitImage === 'string' && explicitImage.trim().length > 0) {
        // If it's not the generic fallback "mission-bg", accept it
        if (!explicitImage.includes('mission-bg')) {
            return explicitImage;
        }
    }

    const cleanKey = (pageKey || '').toLowerCase().trim().replace(/^\//, '').replace(/\/$/, '');
    
    // 1. Direct key match
    if (DOMAIN_HERO_MAP[cleanKey]) {
        return DOMAIN_HERO_MAP[cleanKey];
    }

    // 2. Keyword check on pageKey or title
    const searchTarget = `${cleanKey} ${(title || '')}`.toLowerCase();

    if (searchTarget.includes('computer') || searchTarget.includes('cse') || searchTarget.includes('software') || searchTarget.includes('coding')) {
        return DOMAIN_HERO_MAP['computer-science-and-engineering'];
    }
    if (searchTarget.includes('intelligence') || searchTarget.includes('data science') || searchTarget.includes('ai & ds') || searchTarget.includes('aids')) {
        return DOMAIN_HERO_MAP['artificial-intelligence-and-data-science'];
    }
    if (searchTarget.includes('information tech') || searchTarget.includes(' it ') || searchTarget.endsWith(' it') || searchTarget.startsWith('it ')) {
        return DOMAIN_HERO_MAP['information-technology'];
    }
    if (searchTarget.includes('mechanical') || searchTarget.includes('mech') || searchTarget.includes('automobile') || searchTarget.includes('thermal')) {
        return DOMAIN_HERO_MAP['mechanical-engineering'];
    }
    if (searchTarget.includes('robot') || searchTarget.includes('automation') || searchTarget.includes('mechatronics')) {
        return DOMAIN_HERO_MAP['robotics-and-automation'];
    }
    if (searchTarget.includes('communication') || searchTarget.includes('ece') || searchTarget.includes('vlsi') || searchTarget.includes('embedded')) {
        return DOMAIN_HERO_MAP['electronics-and-communication-engineering'];
    }
    if (searchTarget.includes('electrical') || searchTarget.includes('eee') || searchTarget.includes('power electronics')) {
        return DOMAIN_HERO_MAP['electrical-and-electronics-engineering'];
    }
    if (searchTarget.includes('civil') || searchTarget.includes('structure') || searchTarget.includes('construction') || searchTarget.includes('survey')) {
        return DOMAIN_HERO_MAP['civil-engineering'];
    }
    if (searchTarget.includes('biomedical') || searchTarget.includes('bio-med') || searchTarget.includes('bme')) {
        return DOMAIN_HERO_MAP['biomedical-engineering'];
    }
    if (searchTarget.includes('agri') || searchTarget.includes('farm') || searchTarget.includes('agriculture')) {
        return DOMAIN_HERO_MAP['agricultural-engineering'];
    }
    if (searchTarget.includes('mba') || searchTarget.includes('business') || searchTarget.includes('management') || searchTarget.includes('administration')) {
        return DOMAIN_HERO_MAP['master-of-business-administration'];
    }
    if (searchTarget.includes('science') || searchTarget.includes('humanities') || searchTarget.includes('physics') || searchTarget.includes('chemistry') || searchTarget.includes('math')) {
        return DOMAIN_HERO_MAP['science-and-humanities'];
    }

    // Facilities & Life
    if (searchTarget.includes('place') || searchTarget.includes('career') || searchTarget.includes('recruit') || searchTarget.includes('job') || searchTarget.includes('internship') || searchTarget.includes('ascend')) {
        return DOMAIN_HERO_MAP['placement'];
    }
    if (searchTarget.includes('librar') || searchTarget.includes('book') || searchTarget.includes('journal')) {
        return DOMAIN_HERO_MAP['library'];
    }
    if (searchTarget.includes('sport') || searchTarget.includes('game') || searchTarget.includes('athletic') || searchTarget.includes('ground')) {
        return DOMAIN_HERO_MAP['sports'];
    }
    if (searchTarget.includes('gym') || searchTarget.includes('fitness')) {
        return DOMAIN_HERO_MAP['gym'];
    }
    if (searchTarget.includes('yoga') || searchTarget.includes('meditation') || searchTarget.includes('wellness')) {
        return DOMAIN_HERO_MAP['yoga'];
    }
    if (searchTarget.includes('hostel') || searchTarget.includes('dorm') || searchTarget.includes('residential')) {
        return DOMAIN_HERO_MAP['hostel'];
    }
    if (searchTarget.includes('cafe') || searchTarget.includes('food') || searchTarget.includes('canteen') || searchTarget.includes('dining')) {
        return DOMAIN_HERO_MAP['cafeteria'];
    }
    if (searchTarget.includes('transport') || searchTarget.includes('bus') || searchTarget.includes('fleet')) {
        return DOMAIN_HERO_MAP['transport'];
    }
    if (searchTarget.includes('medical') || searchTarget.includes('health') || searchTarget.includes('clinic')) {
        return DOMAIN_HERO_MAP['medical'];
    }
    if (searchTarget.includes('research') || searchTarget.includes('patent') || searchTarget.includes('idea lab') || searchTarget.includes('coe') || searchTarget.includes('excellence')) {
        return DOMAIN_HERO_MAP['research'];
    }
    if (searchTarget.includes('naac') || searchTarget.includes('nba') || searchTarget.includes('nirf') || searchTarget.includes('aicte') || searchTarget.includes('iqac') || searchTarget.includes('governance') || searchTarget.includes('accredit')) {
        return DOMAIN_HERO_MAP['naac'];
    }
    if (searchTarget.includes('alumni')) {
        return DOMAIN_HERO_MAP['alumni'];
    }
    if (searchTarget.includes('sustain') || searchTarget.includes('sdg') || searchTarget.includes('outreach') || searchTarget.includes('green') || searchTarget.includes('eco')) {
        return DOMAIN_HERO_MAP['sustainability'];
    }
    if (searchTarget.includes('scholarship') || searchTarget.includes('fee') || searchTarget.includes('admission') || searchTarget.includes('enroll')) {
        return DOMAIN_HERO_MAP['scholarship'];
    }
    if (searchTarget.includes('club') || searchTarget.includes('fest') || searchTarget.includes('dhruva') || searchTarget.includes('gallery') || searchTarget.includes('event')) {
        return DOMAIN_HERO_MAP['dhruva-fest'];
    }

    // Default Campus Architecture Hero
    return DOMAIN_HERO_MAP['institution'];
};

export default getDomainHeroImage;
